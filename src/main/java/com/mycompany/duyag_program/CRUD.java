    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {

    String sql = "INSERT INTO Students (Name, Age, Course) VALUES (?, ?, ?)";

    try {

        pst = conn.prepareStatement(sql);

        pst.setString(1, txt_name.getText());
        pst.setInt(2, Integer.parseInt(txt_age.getText()));
        pst.setString(3, txt_course.getText());

        pst.executeUpdate();

JOptionPane.showMessageDialog(
    this,
    "Record added successfully!"
);

loadData();
clearFields();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error adding record: " + e.getMessage()
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Age must be a number."
        );
    }
}

    private void btn_editActionPerformed(java.awt.event.ActionEvent evt) {

    String sql =
        "UPDATE Students SET Name = ?, Age = ?, Course = ? WHERE ID = ?";

    try {

        pst = conn.prepareStatement(sql);

        pst.setString(1, txt_name.getText());
        pst.setInt(2, Integer.parseInt(txt_age.getText()));
        pst.setString(3, txt_course.getText());
        pst.setInt(4, Integer.parseInt(txt_id.getText()));

        int updated = pst.executeUpdate();

        if (updated > 0) {

    JOptionPane.showMessageDialog(
        this,
        "Record updated successfully!"
    );

    loadData();
    clearFields();

} else {
    JOptionPane.showMessageDialog(
        this,
        "Record not found."
    );
}

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error updating record: " + e.getMessage()
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "ID and Age must be numbers."
        );
    }finally {

        try {
            if (rs != null) {
                rs.close();
            }

            if (pst != null) {
                pst.close();
            }

        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }    
}

    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {

    String sql = "DELETE FROM Students WHERE ID = ?";

    try {

        pst = conn.prepareStatement(sql);

        pst.setInt(1, Integer.parseInt(txt_id.getText()));

        int deleted = pst.executeUpdate();

        if (deleted > 0) {

    JOptionPane.showMessageDialog(
        this,
        "Record deleted successfully!"
    );

    loadData();
    clearFields();

} else {
    JOptionPane.showMessageDialog(
        this,
        "Record not found."
    );
}

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error deleting record: " + e.getMessage()
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter a valid ID."
        );
    }
}

    private void loadData() {

    String sql = "SELECT * FROM Students";

    try {

        pst = conn.prepareStatement(sql);
        rs = pst.executeQuery();

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tbl_students.getModel();

        model.setRowCount(0);

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("ID"),
                rs.getString("Name"),
                rs.getInt("Age"),
                rs.getString("Course")
            });
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error loading records: " + e.getMessage()
        );
    }
}

