    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = table.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a student to update.");
        return;
    }

    String oldId = table.getValueAt(row, 0).toString();
    String id = txtId.getText().trim();
    String name = txtName.getText().trim();
    String course = txtCourse.getText().trim();
    String ageText = txtAge.getText().trim();

    if (id.isEmpty() || name.isEmpty()
            || course.isEmpty() || ageText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please fill in all fields.");
        return;
    }

    int age;

    try {
        age = Integer.parseInt(ageText);
        if (age <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Age must be greater than zero.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Age must be a valid whole number.");
        return;
    }

    String sql = "UPDATE Students1 SET StudentID=?, "
           + "StudentName=?, Course=?, Age=? "
           + "WHERE StudentID=?";

    try (Connection c = MsConnectAccess.conn()) {
        if (c == null) {
            JOptionPane.showMessageDialog(this,
                    "Unable to connect to the database.");
            return;
        }

        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, id);
            ps.setString(2, name);
            ps.setString(3, course);
            ps.setInt(4, age);
            ps.setString(5, oldId);

            int affected = ps.executeUpdate();

            if (affected > 0) {
                loadStudents();
                clearFields();
                JOptionPane.showMessageDialog(this,
                        "Student updated successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Student record not found.");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error updating student: " + e.getMessage());
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int row = table.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a student to delete.");
        return;
    }

    String id = table.getValueAt(row, 0).toString();

    int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this student?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "DELETE FROM Students1 WHERE StudentID=?";

    try (Connection c = MsConnectAccess.conn()) {
        if (c == null) {
            JOptionPane.showMessageDialog(this,
                    "Unable to connect to the database.");
            return;
        }

        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, id);

            int affected = ps.executeUpdate();

            if (affected > 0) {
                loadStudents();
                clearFields();
                JOptionPane.showMessageDialog(this,
                        "Student deleted successfully!");
            } else {
                JOptionPane.showMessageDialog(this,
                        "Student record not found.");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error deleting student: " + e.getMessage());
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

